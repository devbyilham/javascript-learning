let hari = 3;

switch (hari) {
  case 1:
    console.log("senin");
    break;

  case 2:
    console.log("Selasa");
    break;

  case 3:
    console.log("Rabu");
    break;

  case 4:
    console.log("Kamis");
    break;

  case 5:
    console.log("Jumat");
    break;

  default:
    console.log("Hari tidak ditemukan");
}
